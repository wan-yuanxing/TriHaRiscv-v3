"""Generate CPU board constraints from the single board configuration."""
import argparse
from fractions import Fraction
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
CONFIG = ROOT / "config/cpu_board.json"
OUTPUT = ROOT / "fpga/pg2l100h/constraints/cpu_board.fdc"
PORTS = {"ref_clk_pi", "ref_clk_ni", "rst_ni", "uart_tx_o", *(f"led_o[{i}]" for i in range(4))}


def validate(config):
    if config["schema_version"] != 1 or config["top"] != "triha_cpu_board_top":
        raise ValueError("unsupported CPU board configuration")
    if set(config["pins"]) != PORTS:
        raise ValueError("board ports do not match the actual top")
    locations = [pin["location"] for pin in config["pins"].values()]
    if len(locations) != len(set(locations)):
        raise ValueError("duplicate board pin")
    pll = config["pll"]
    for key in ("input_divider", "multiplier", "feedback_divider", "output_divider"):
        if type(pll[key]) is not int or not 1 <= pll[key] <= 128:
            raise ValueError("invalid integer PLL divider")
    pfd = Fraction(config["reference_hz"], pll["input_divider"])
    if not 10_000_000 <= pfd <= 450_000_000:
        raise ValueError("PLL PFD outside 10..450MHz")
    vco = pfd * pll["multiplier"] * pll["feedback_divider"]
    if not 600_000_000 <= vco <= 1_200_000_000:
        raise ValueError("PLL VCO outside 600..1200MHz")
    actual = vco / pll["output_divider"]
    if actual != config["cpu_hz"] or actual != 100_000_000:
        raise ValueError("PLL does not generate exact 100MHz")
    if config["reference_hz"] != 125_000_000 or pll["instance"] != "cpu_board_pll":
        raise ValueError("wrong board reference clock or instance")
    return pfd, vco, actual


def generate(config, output=OUTPUT, check=False):
    validate(config)
    lines = ["# Generated by scripts/soc/gen_board.py; edit config/cpu_board.json.",
             "# Actual 125MHz N3/N2 board oscillator -> 100MHz PLL; no timing exceptions."]
    for port, pin in config["pins"].items():
        attributes = {"PAP_IO_LOC": pin["location"], "PAP_IO_DIRECTION": pin["direction"],
                      "PAP_IO_VCCIO": pin["vccio"], "PAP_IO_STANDARD": pin["standard"], "PAP_IO_NONE": "TRUE"}
        if pin["direction"] == "OUTPUT":
            attributes.update(PAP_IO_DRIVE="8", PAP_IO_SLEW="SLOW")
        lines += [f"define_attribute {{p:{port}}} {{{name}}} {{{value}}}" for name, value in attributes.items()]
    lines += [
        "create_clock -name ref_clk -period 8.000 [get_ports {ref_clk_pi}]",
        "create_generated_clock -name cpu_clk -source [get_ports {ref_clk_pi}] -multiply_by 4 -divide_by 5 [get_pins {u_clocks.u_pll/clkout0}]",
        "set_clock_uncertainty 0.100 -from [get_clocks {cpu_clk}] -to [get_clocks {cpu_clk}] -setup",
        "set_clock_uncertainty 0.050 -from [get_clocks {cpu_clk}] -to [get_clocks {cpu_clk}] -hold",
        "set_input_delay 2.000 -clock [get_clocks {cpu_clk}] -max [get_ports {rst_ni}]",
        "set_input_delay 0.500 -clock [get_clocks {cpu_clk}] -min [get_ports {rst_ni}]",
        "set_output_delay 2.000 -clock [get_clocks {cpu_clk}] -max [get_ports {uart_tx_o led_o*}]",
        "set_output_delay 0.500 -clock [get_clocks {cpu_clk}] -min [get_ports {uart_tx_o led_o*}]",
        "define_global_attribute {syn_useioff} {1}",
    ]
    data = ("\n".join(lines) + "\n").encode("utf-8")
    if check:
        if not output.is_file() or output.read_bytes() != data:
            raise ValueError("generated board constraints drift")
    else:
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_bytes(data)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        cfg = json.loads(CONFIG.read_text(encoding="utf-8"))
        soc = json.loads((ROOT / "config/soc_map.json").read_text(encoding="utf-8"))
        if cfg["cpu_hz"] != soc["clock_hz"]:
            raise ValueError("board/system clock mismatch")
        generate(cfg, check=args.check)
        print("CPU_BOARD_CONFIG_PASS")
    except (OSError, ValueError, KeyError) as error:
        print("CPU_BOARD_CONFIG_FAIL:", error, file=sys.stderr)
        raise SystemExit(1)
