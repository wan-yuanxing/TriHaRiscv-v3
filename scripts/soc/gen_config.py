"""Generate the minimal-system definitions from the authoritative address map."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def generate(check=False):
    m = json.loads((ROOT / "config/soc_map.json").read_text(encoding="utf-8"))
    assert m["schema_version"] == 1
    assert (m["rom_base"], m["rom_bytes"], m["sram_base"], m["sram_bytes"]) == (0, 8192, 65536, 32768)
    regions = [(m["rom_base"], m["rom_bytes"]), (m["sram_base"], m["sram_bytes"]),
               (m["uart_base"], 8), (m["system_base"], 12)]
    for index, (base, size) in enumerate(regions):
        assert base % 4 == 0 and 0 <= base < base + size <= 2**32
        for other, length in regions[index + 1:]:
            if base < other + length and other < base + size:
                raise ValueError("Address map overlap: local and MMIO windows must be disjoint")
    vh = "// Generated by scripts/soc/gen_config.py; do not edit.\n"
    header = "/* Generated from config/soc_map.json; do not edit. */\n#pragma once\n"
    for key, value in m.items():
        if isinstance(value, int) and key != "schema_version":
            vh += f"`define TRIHA_{key.upper()} 32'h{value:08x}\n"
            header += f"#define TRIHA_{key.upper()} 0x{value:08x}u\n"
    link = f"""/* Generated SRAM execution image; ROM jumps to _start. */
ENTRY(_start)
MEMORY {{ RAM (rwx) : ORIGIN = 0x{m['sram_base']:08x}, LENGTH = {m['sram_bytes']} }}
__stack_top = ORIGIN(RAM) + LENGTH(RAM);
__stack_bottom = __stack_top - {m['stack_bytes']};
SECTIONS {{
    .text : ALIGN(4) {{ KEEP(*(.init)) *(.text*) *(.rodata*) }} > RAM
    .data : ALIGN(4) {{ __data_start = .; *(.sdata*) *(.data*) __data_end = .; }} > RAM
    __global_pointer$ = __data_start + 0x800;
    .bss (NOLOAD) : ALIGN(4) {{ __bss_start = .; *(.sbss*) *(.bss*) *(COMMON) . = ALIGN(4); __bss_end = .; }} > RAM
    /DISCARD/ : {{ *(.eh_frame*) }}
    ASSERT(__bss_end <= __stack_bottom, "SRAM image overlaps 4KiB stack")
}}
"""
    for name, text in {"rtl/soc/include/soc_map.vh": vh, "sw/runtime/soc_map.h": header,
                       "sw/runtime/triha_sram.ld": link}.items():
        path = ROOT / name
        data = text.encode("utf-8")
        if check:
            if not path.is_file() or path.read_bytes() != data:
                raise ValueError(f"Generated configuration drift: {name}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    generate(parser.parse_args().check)
    print("SOC_CONFIG_PASS")
