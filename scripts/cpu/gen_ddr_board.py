"""Generate the opt-in CPU/DDR board parameters, pins and scoped CDC constraints."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def generated(root=ROOT):
    root = Path(root)
    cfg = json.loads((root/'config/cpu_ddr_board.json').read_text(encoding='utf-8'))
    cpu = json.loads((root/cfg['cpu_board_config']).read_text(encoding='utf-8'))
    ddr = json.loads((root/cfg['ddr_manifest']).read_text(encoding='utf-8'))
    if (cfg['schema_version'] != 1 or cfg['free_clock_hz'] != 27000000 or
            cpu['cpu_hz'] != 100000000 or cpu['reference_hz'] != ddr['reference_hz'] or
            ddr['core_hz'] != 125000000 or cfg['cpu_period_ns'] != 10.0 or
            cfg['gray_max_delay_ns'] != 8.0 or cfg['gray_max_skew_ns'] != 2.0):
        raise ValueError('board clock/CDC contract mismatch')
    if (cfg['private_test_base'],cfg['shared_test_base'],cfg['test_words']) != (0x80010000,0x87300000,2048):
        raise ValueError('exclusive diagnostic scratch window mismatch')
    base = (root/cfg['pin_template']).read_text(encoding='utf-8')
    text = base.split('# Bounded bundled-data CDC.')[0]
    names = {'ref_clk_p':'ref_clk_pi','ref_clk_n':'ref_clk_ni','sys_clk':'sys_clk_i',
        'rst_in':'rst_ni','uart_tx':'uart_tx_o','heart_beat_led':'led_o[0]',
        'ddr_init_done':'led_o[1]','init_over_rx':'led_o[2]','hdmi_int_led':'led_o[3]'}
    for old,new in names.items():
        text = text.replace('{'+old+'}', '{'+new+'}').replace('{p:'+old+'}', '{p:'+new+'}')
    text = '# Generated by scripts/cpu/gen_ddr_board.py; physical DDR pin/PHY constraints retained.\n'+text
    text += '''
# Actual shared125MHz reference -> CPU100MHz PLL, original CPU IO/hold budgets.
create_generated_clock -name cpu_clk -source [get_ports {ref_clk_pi}] -multiply_by 4 -divide_by 5 [get_pins {u_cpu_pll/clkout0}]
set_clock_uncertainty 0.100 -from [get_clocks {cpu_clk}] -to [get_clocks {cpu_clk}] -setup
set_clock_uncertainty 0.050 -from [get_clocks {cpu_clk}] -to [get_clocks {cpu_clk}] -hold
set_input_delay 2.000 -clock [get_clocks {cpu_clk}] -max [get_ports {rst_ni}]
set_input_delay 0.500 -clock [get_clocks {cpu_clk}] -min [get_ports {rst_ni}]
set_output_delay 2.000 -clock [get_clocks {cpu_clk}] -max [get_ports {uart_tx_o}]
set_output_delay 0.500 -clock [get_clocks {cpu_clk}] -min [get_ports {uart_tx_o}]
set_output_delay 2.000 -clock [get_clocks {free_clk}] -max [get_ports {led_o*}]
set_output_delay 0.500 -clock [get_clocks {free_clk}] -min [get_ports {led_o*}]
define_global_attribute {syn_useioff} {1}

# Only asynchronous first-stage D pins; second-stage synchronizers remain timed.
set_false_path -to [get_pins {u_system.u_cdc.ready_meta_q/D* u_system.u_cdc.fault_meta_q/D* u_supervisor.status_meta_q*/D* u_supervisor.beat_meta_q/D* software_meta_q*/D* board_fault_meta_q/D*}]
# Free-domain epoch launch reaches asynchronous reset pins only. Same-domain
# release-register recovery/removal and all D/CE/RAM data paths remain timed.
set_false_path -from [get_ports {rst_ni}] -to [get_pins {u_supervisor.free_release_q*/C}]
set_false_path -from [get_clocks {free_clk}] -to [get_pins {u_supervisor.ddr_release_q*/C u_system.u_cdc.cpu_release_q*/C u_system.u_cdc.ddr_release_q*/C I_ips_ddr_top.u_ddrc_rstn_sync.sig_async_r*/C}]
# Preserve the pinned vendor phase-adjust reset protocol and startup hold.
set_false_path -from [get_clocks {free_clk}] -to [get_pins {I_ips_ddr_top.u_ddrphy_top.u_ips2l_ddrphy_rst_clk_phase_adj.*/C I_ips_ddr_top.u_ddrphy_top.u_ips2l_ddrphy_rst_clk_phase_adj.*/P}]
'''
    for channel in ['aw','w','b','ar','r']:
        scope = 'u_system/u_cdc/u_'+channel+'_fifo/'
        for source,dest in [('wr_gray','wr_gray_rd_sync1'),('rd_gray','rd_gray_wr_sync1')]:
            # PDS uses wide cells wr_gray[2:0]/Q[bit] before technology
            # mapping and wr_gray[bit]/Q afterwards. Match both exact base
            # names, excluding wr_gray_rd_sync1/2 and every control pin.
            launch = scope+source+r'\[[0-9:]+\]/Q(\[[0-9]+\])?'
            capture = scope+dest+r'\[[0-9:]+\]/D(\[[0-9]+\])?'
            path = '-from [get_pins -regexp -hsc / {'+launch+'}] -to [get_pins -regexp -hsc / {'+capture+'}]'
            text += f'set_max_delay 8.000 -datapath_only {path}\n'
            text += f'set_max_skew 2.000 {path}\n'
            text += f'set_false_path -hold {path}\n'
    values = {k.upper():cfg[k] for k in ['startup_cycles','init_timeout_cycles','clock_timeout_cycles','heartbeat_cycles']}
    vh = '// Generated by scripts/cpu/gen_ddr_board.py.\n'
    vh += ''.join(f'`define TRIHA_DDR_BOARD_{k} {v}\n' for k,v in values.items())
    c = '/* Generated by scripts/cpu/gen_ddr_board.py. */\n#ifndef TRIHA_CPU_DDR_BOARD_H\n#define TRIHA_CPU_DDR_BOARD_H\n'
    c += ''.join(f'#define TRIHA_DDR_BOARD_{key.upper()} 0x{cfg[key]:08x}u\n' for key in ['private_test_base','shared_test_base','test_words'])+'#endif\n'
    return {'fpga/pg2l100h/constraints/cpu_ddr_board.fdc':text,
            'rtl/soc/include/cpu_ddr_board_cfg.vh':vh, 'sw/runtime/cpu_ddr_board.h':c}


def generate(check=False):
    for name,text in generated().items():
        path = ROOT/name
        if check:
            if not path.is_file() or path.read_bytes() != text.encode('utf-8'):
                raise ValueError('stale generated board file: '+name)
        else:
            path.write_text(text, encoding='utf-8', newline='\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    generate(args.check)
    print('CPU_DDR_BOARD_CONFIG_PASS')
