"""Generate the opt-in cached CPU system's small shared RTL/C address header."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def generated(root=ROOT):
    root = Path(root)
    spec = json.loads((root/'config/cpu_cache_soc.json').read_text(encoding='utf-8'))
    if spec['schema_version'] != 1 or spec['local_config'] != 'config/soc_map.json' or spec['cache_config'] != 'config/cpu_cache.json':
        raise ValueError('unsupported Cache system configuration paths/schema')
    local = json.loads((root/spec['local_config']).read_text(encoding='utf-8'))
    cache = json.loads((root/spec['cache_config']).read_text(encoding='utf-8'))
    if (local['clock_hz'] != 100000000 or cache['clock_hz'] != local['clock_hz'] or
            spec['clock_domain'] != 'cpu_clk' or spec['ddr_interface_clock_domain'] != 'cpu_clk'):
        raise ValueError('CPU and external AXI boundary must use the same declared clock')
    if spec['fault_recovery'] != 'coordinated_cpu_cache_fabric_ddr_reset':
        raise ValueError('fault recovery requires coordinated CPU/cache/fabric/DDR reset')
    if spec['ddr_status_offset'] != 12 or spec['ddr_status_ready_mask'] != 1 or spec['ddr_status_fault_mask'] != 2:
        raise ValueError('read-only DDR status ABI mismatch')
    if cache['private_ddr_base']+cache['private_ddr_bytes'] != cache['shared_ddr_base']:
        raise ValueError('private/shared DDR address windows must be contiguous')
    values = dict(TRIHA_CPU_DDR_BASE=cache['private_ddr_base'],
                  TRIHA_CPU_DDR_END=cache['shared_ddr_base']+cache['shared_ddr_bytes'],
                  TRIHA_CPU_DDR_STATUS_ADDR=local['system_base']+spec['ddr_status_offset'],
                  TRIHA_CPU_DDR_READY=spec['ddr_status_ready_mask'],
                  TRIHA_CPU_DDR_FAULT=spec['ddr_status_fault_mask'])
    if values['TRIHA_CPU_DDR_BASE'] != 0x80000000 or values['TRIHA_CPU_DDR_END'] != 0x88000000:
        raise ValueError('DDR window exceeds current system contract')
    v = '// Generated by scripts/cpu/gen_cache_soc.py; edit config, not this file.\n'
    v += '`ifndef TRIHA_CPU_CACHE_MAP_VH\n`define TRIHA_CPU_CACHE_MAP_VH\n'
    v += ''.join(f"`define {name} 32'h{value:08x}\n" for name,value in values.items())+'`endif\n'
    c = '/* Generated by scripts/cpu/gen_cache_soc.py; edit config, not this file. */\n'
    c += '#ifndef TRIHA_CPU_CACHE_MAP_H\n#define TRIHA_CPU_CACHE_MAP_H\n'
    c += ''.join(f'#define {name} 0x{value:08x}u\n' for name,value in values.items())+'#endif\n'
    return {'rtl/soc/include/cpu_cache_map.vh':v,'sw/runtime/cpu_cache_map.h':c}


def generate(check=False):
    for name,text in generated().items():
        path = ROOT/name
        if check:
            if not path.is_file() or path.read_bytes() != text.encode('utf-8'):
                raise ValueError('stale/missing generated Cache system header: '+name)
        else:
            path.write_text(text,encoding='utf-8',newline='\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check',action='store_true')
    args = parser.parse_args()
    generate(args.check)
    print('CPU_CACHE_SOC_CONFIG_PASS')
