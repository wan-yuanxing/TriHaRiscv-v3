"""Generate fixed-mode RTL/C constants from config/video_cfg.json."""
import argparse
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]


def validate(config):
    # These are the v0.6 acceptance bounds, not a second editable mode table.
    fixed = {
        "mode": {"pixel_hz": 40000000, "h_active": 800, "h_front": 40,
                 "h_sync": 128, "h_back": 88, "v_active": 600, "v_front": 1,
                 "v_sync": 4, "v_back": 23, "hsync_positive": True,
                 "vsync_positive": True},
        "preview": {"width": 400, "height": 300, "left_x": 0,
                    "right_x": 400, "y": 150, "bytes_per_pixel": 3},
        "detector": {"active_width": 160, "active_height": 120,
                     "storage_height": 128, "valid_channels": 3,
                     "storage_channels": 8, "channel_order": "BGR",
                     "quantization_owner": "model/yunet/model_manifest"},
    }
    expected = {"schema_version": 1, "spec_version": "0.6", **fixed}
    # JSON type matters: Python otherwise considers True equal to 1.
    if json.dumps(config, sort_keys=True) != json.dumps(expected, sort_keys=True):
        raise ValueError("configuration violates fixed v0.6 mode/layout contract")


def constants(config):
    mode = config["mode"]
    values = {name.upper(): int(value) for name, value in mode.items()}
    for axis in ("h", "v"):
        values[f"{axis.upper()}_TOTAL"] = sum(
            mode[f"{axis}_{part}"] for part in ("active", "front", "sync", "back"))
    values.update({f"PREVIEW_{name.upper()}": value
                   for name, value in config["preview"].items()})
    values["PREVIEW_BYTES"] = (config["preview"]["width"] *
                               config["preview"]["height"] *
                               config["preview"]["bytes_per_pixel"])
    values["INPUT_BYTES"] = (config["detector"]["active_width"] *
                             config["detector"]["storage_height"] *
                             config["detector"]["storage_channels"])
    return values


def generated_files(config, digest):
    note = f"// Generated by scripts/video/gen_config.py; config SHA256 {digest}\n"
    values = constants(config)
    rtl = note + "`ifndef TRIHA_VIDEO_CFG_VH\n`define TRIHA_VIDEO_CFG_VH\n"
    c = note + "#ifndef TRIHA_VIDEO_CFG_H\n#define TRIHA_VIDEO_CFG_H\n"
    for name, value in values.items():
        rtl += f"`define VIDEO_{name} {value}\n"
        c += f"#define VIDEO_{name} {value}u\n"
    return {"rtl/video/include/video_cfg.vh": rtl + "`endif\n",
            "sw/include/video_cfg.h": c + "#endif\n"}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=ROOT)
    parser.add_argument("--config", type=Path, default=ROOT / "config/video_cfg.json")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        source = args.config.read_bytes()
        config = json.loads(source)
        validate(config)
        digest = hashlib.sha256(source).hexdigest()
        stale = []
        for relative, content in generated_files(config, digest).items():
            path = args.root / relative
            if args.check:
                if not path.is_file() or path.read_bytes() != content.encode("utf-8"):
                    stale.append(relative)
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(content.encode("utf-8"))
        if stale:
            raise ValueError("missing/stale generated definitions: " + ", ".join(stale))
    except (OSError, ValueError, TypeError, KeyError) as error:
        print(f"VIDEO_CONFIG_FAIL: {error}", file=sys.stderr)
        return 1
    print("VIDEO_CONFIG_PASS" + (" check" if args.check else " generate"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
