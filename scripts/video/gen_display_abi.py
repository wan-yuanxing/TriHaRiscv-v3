"""Generate the independent display subwindow and full-record RTL/C ABI."""
import argparse,hashlib,json,re,sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
FINGERPRINT='5beda09507ee5860161714f0c8f3fa08e14ecb3accc6202b7a293086e6d64e7b'
def unique_object(pairs):
    out={}
    for key,value in pairs:
        if key in out:raise ValueError('duplicate JSON key: '+key)
        out[key]=value
    return out
def validate(cfg):
    if type(cfg) is not dict:raise ValueError('profile must be an object')
    encoded=json.dumps(cfg,sort_keys=True,separators=(',',':')).encode('utf-8')
    if hashlib.sha256(encoded).hexdigest()!=FINGERPRINT:
        raise ValueError('display ABI drift or invalid type; publish a reviewed version')
def generated_files(cfg,digest):
    validate(cfg)
    if not re.fullmatch('[0-9a-f]{64}',digest):raise ValueError('invalid digest')
    values={'BASE':cfg['base'],'REGION_BYTES':cfg['region_bytes'],'VERSION':cfg['abi_version'],
            'CAPABILITIES':cfg['capabilities'],'RECORD_WORDS':cfg['record_words'],
            'RECORD_BYTES':cfg['record_words']*4,'RECORD_BITS':cfg['record_words']*32,
            'HEADER_WORDS':cfg['header_words'],'BOX_COUNT':cfg['box_count'],
            'BOX_WORDS':cfg['box_words'],'SHADOW_OFFSET':cfg['shadow_offset']}
    for table,prefix in [('registers','REG_'),('fields','FIELD_'),('flags','FLAG_')]:
        values.update({prefix+k:v for k,v in sorted(cfg[table].items())})
    note='// Generated by scripts/video/gen_display_abi.py; config SHA256 '+digest+'\n'
    rtl=note+'`ifndef TRIHA_VIDEO_DISPLAY_VH\n`define TRIHA_VIDEO_DISPLAY_VH\n'
    c=note+'#ifndef TRIHA_VIDEO_DISPLAY_ABI_H\n#define TRIHA_VIDEO_DISPLAY_ABI_H\n'
    for key,value in values.items():
        rtl+=f"`define VDISP_{key} 32'h{value:08x}\n"
        c+=f'#define VDISP_{key} 0x{value:08x}u\n'
    return {'rtl/video/include/video_display.vh':rtl+'`endif\n','sw/include/video_display_abi.h':c+'#endif\n'}
def main(argv=None):
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root',type=Path,default=ROOT)
    parser.add_argument('--config',type=Path,default=ROOT/'config/video_display.json')
    parser.add_argument('--check',action='store_true');args=parser.parse_args(argv)
    try:
        raw=args.config.read_bytes();cfg=json.loads(raw,object_pairs_hook=unique_object)
        files=generated_files(cfg,hashlib.sha256(raw).hexdigest())
        stale=[]
        for name,content in files.items():
            path=args.root/name;data=content.encode('utf-8')
            if args.check:
                if not path.is_file() or path.read_bytes()!=data:stale.append(name)
            else:path.parent.mkdir(parents=True,exist_ok=True);path.write_bytes(data)
        if stale:raise ValueError('missing/stale display definitions: '+', '.join(stale))
    except (OSError,ValueError,TypeError,KeyError) as error:
        print('DISPLAY_ABI_FAIL:',error,file=sys.stderr);return 1
    print('DISPLAY_ABI_PASS'+(' check' if args.check else ' generate'));return 0
if __name__=='__main__':raise SystemExit(main())
