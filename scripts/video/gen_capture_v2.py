"""Generate the independent capture ABI2 from the frozen JSON profile."""
import argparse,hashlib,json,re,sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
FINGERPRINT='97acf7de3c55950306c981a5be21181bbd0c744d173a97d2da7d14c4e4494a52'
def unique_object(pairs):
    out={}
    for key,value in pairs:
        if key in out:raise ValueError('duplicate JSON key: '+key)
        out[key]=value
    return out
def validate(cfg):
    if type(cfg) is not dict:raise ValueError('profile must be an object')
    encoded=json.dumps(cfg,sort_keys=True,separators=(',',':')).encode('utf-8')
    if hashlib.sha256(encoded).hexdigest()!=FINGERPRINT:
        raise ValueError('capture ABI2 drift or invalid type; publish a reviewed version')
def generated_files(cfg,digest):
    validate(cfg)
    if not re.fullmatch('[0-9a-f]{64}',digest):raise ValueError('invalid digest')
    values={'MMIO_BASE':cfg['base'],'MMIO_BYTES':cfg['region_bytes'],'ABI_VERSION':cfg['abi_version'],
            'CAPABILITIES':sum(1<<v for v in cfg['capabilities'].values())}
    for name,bit in sorted(cfg['capabilities'].items()):values['CAP_'+name]=1<<bit
    for name,bit in sorted(cfg.get('optional_capabilities',{}).items()):values['CAP_'+name]=1<<bit
    for reg in sorted(cfg['registers'],key=lambda r:r['offset']):
        name=reg['name'];values['REG_'+name]=reg['offset']
        if 'reset' in reg:values['REG_'+name+'_RESET']=reg['reset']
        for f in reg['fields']:
            prefix=name+'_'+f['name'];values[prefix+'_MASK']=((1<<f['width'])-1)<<f['lsb'];values[prefix+'_SHIFT']=f['lsb']
    note='// Generated by scripts/video/gen_capture_v2.py; config SHA256 '+digest+'\n'
    rtl=note+'`ifndef TRIHA_VIDEO_CAPTURE_V2_VH\n`define TRIHA_VIDEO_CAPTURE_V2_VH\n'
    c=note+'#ifndef TRIHA_VIDEO_CAPTURE_V2_ABI_H\n#define TRIHA_VIDEO_CAPTURE_V2_ABI_H\n'
    for key,value in values.items():
        rtl+=f"`define VCAP_{key} 32'h{value:08x}\n"
        c+=f'#define VCAP_{key} 0x{value:08x}u\n'
    return {'rtl/video/include/video_capture_v2.vh':rtl+'`endif\n','sw/include/video_capture_v2.h':c+'#endif\n'}
def main(argv=None):
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root',type=Path,default=ROOT)
    parser.add_argument('--config',type=Path,default=ROOT/'config/video_capture_v2.json')
    parser.add_argument('--check',action='store_true');args=parser.parse_args(argv)
    try:
        raw=args.config.read_bytes();cfg=json.loads(raw,object_pairs_hook=unique_object)
        files=generated_files(cfg,hashlib.sha256(raw).hexdigest())
        stale=[]
        for name,content in files.items():
            path=args.root/name;data=content.encode('utf-8')
            if args.check:
                if not path.is_file() or path.read_bytes()!=data:stale.append(name)
            else:path.parent.mkdir(parents=True,exist_ok=True);path.write_bytes(data)
        if stale:raise ValueError('missing/stale capture ABI2 definitions: '+', '.join(stale))
    except (OSError,ValueError,TypeError,KeyError) as error:
        print('CAPTURE_V2_ABI_FAIL:',error,file=sys.stderr);return 1
    print('CAPTURE_V2_ABI_PASS'+(' check' if args.check else ' generate'));return 0
if __name__=='__main__':raise SystemExit(main())
