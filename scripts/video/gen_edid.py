"""Generate the fixed 800x600 DMT 09h EDID and a synthesis-safe byte function.

Both outputs are deterministic and checked together. The 256-byte configuration
image includes an unused zeroed second block so all vendor EDID RAM writes can
be retained while removing the vendor's HDMI extension and higher video modes.
"""
import argparse
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
HEX = ROOT / "config/video_edid.hex"
INCLUDE = ROOT / "rtl/video/include/video_edid.vh"


def fixed_image():
    image = bytearray(256)
    image[:8] = bytes.fromhex("00 ff ff ff ff ff ff 00")
    image[8:18] = bytes.fromhex("3c 29 08 06 01 00 00 00 01 24")
    image[18:25] = bytes((1, 3, 0x80, 32, 24, 120, 0x0a))
    image[25:35] = bytes.fromhex("0a d5 a9 55 4f 9e 25 0c 50 54")
    image[35] = 1  # The sole established timing: 800x600 at 60 Hz.
    image[38:54] = bytes((1, 1)) * 8  # All standard timing entries unused.
    # VESA DMT 09h: 40 MHz; H 800/40/128/88; V 600/1/4/23; +H/+V.
    image[54:72] = bytes.fromhex("a0 0f 20 00 31 58 1c 20 28 80 14 00 40 f0 10 00 00 1e")
    image[72:90] = bytes.fromhex("00 00 00 fc 00") + b"TriHa SVGA  \n"
    image[90:108] = bytes.fromhex("00 00 00 fe 00") + b"DMT 09h ONLY\n"
    image[108:126] = bytes.fromhex("00 00 00 10 00") + bytes(13)
    image[126] = 0
    image[127] = (-sum(image[:127])) & 0xff
    return bytes(image)


def outputs():
    image = fixed_image()
    hex_text = "".join(f"{byte:02x}\n" for byte in image)
    lines = ["// Generated by scripts/video/gen_edid.py. Do not edit.",
             "// 128-byte EDID, no extensions; unused second RAM block is zero.",
             "function automatic [7:0] video_edid_byte(input [7:0] index);",
             "    begin", "        case (index)"]
    lines += [f"            8'h{index:02x}: video_edid_byte = 8'h{byte:02x};"
              for index, byte in enumerate(image[:128])]
    lines += ["            default: video_edid_byte = 8'h00;", "        endcase",
              "    end", "endfunction", ""]
    return {HEX: hex_text, INCLUDE: "\n".join(lines)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for path, expected in outputs().items():
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != expected:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected, encoding="utf-8", newline="\n")
    if stale:
        print("VIDEO_EDID_STALE: " + ", ".join(stale))
        return 1
    print("VIDEO_EDID_CHECK_PASS" if args.check else "VIDEO_EDID_GENERATED")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
