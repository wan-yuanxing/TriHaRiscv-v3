"""Recover immutable B03 assets; partial recovery is explicit and exits 2."""
import argparse
import ast
from datetime import datetime, timezone
import json
from pathlib import Path
import re
import subprocess
import sys
import struct

from audit_b03_assets import (CASES, MANIFEST_PATH, MANIFEST_SHA256, REVISION,
                              audit_assets, digest, load_manifest, require, safe_path)

ROOT = Path(__file__).resolve().parents[2]
OLD = 'yunet/reports/program_abi_v0_1_checked'
BASE_MANIFEST = 'yunet/baseline/program_package_manifest_v0_1.json'
NUMERICS = 'yunet/models/integer_numerics_v1.json'
POST = 'yunet/baseline/b03_post_reference_v0_2.json'
HEAD_MAP = 'yunet/baseline/b03_m01_review_v0_1.json'
HEAD_GOLD = 'yunet/baseline/ptq_integer_golden_summary_v1.json'


def freeze_file(source, destination, expected_sha256):
    destination = Path(destination)
    require(not destination.exists(), 'frozen destination already exists')
    raw = Path(source).read_bytes()
    require(digest(raw) == expected_sha256, 'source SHA mismatch: ' + str(source))
    destination.parent.mkdir(parents=True, exist_ok=True)
    with destination.open('xb') as stream:
        stream.write(raw)
    require(digest(destination.read_bytes()) == expected_sha256, 'frozen copy SHA mismatch')


def verify_frozen(root, records):
    for name, expected in records.items():
        path = safe_path(root, name)
        require(path.is_file() and digest(path.read_bytes()) == expected, 'frozen source changed: ' + name)


def freeze_git_inputs(repo, revision, paths, destination, expected):
    require(re.fullmatch('[0-9a-f]{40}', revision), 'use a full commit ID, never a mutable Git ref')
    records = {}
    for name in paths:
        path = safe_path(destination, name)
        require(not path.exists(), 'frozen destination already exists: ' + name)
        data = subprocess.check_output(['git', '-C', str(repo), 'show', revision + ':' + name])
        sha256 = digest(data)
        require(name not in expected or expected[name] == sha256, 'Git object SHA mismatch: ' + name)
        path.parent.mkdir(parents=True, exist_ok=True)
        with path.open('xb') as stream:
            stream.write(data)
        records[name] = sha256
    verify_frozen(destination, records)
    return records


def write_historical(root, name, data, hashes):
    require(name in hashes and digest(data) == hashes[name], 'generated bytes differ from historical asset: ' + name)
    path = safe_path(root, name)
    if path.exists():
        require(path.read_bytes() == data, 'historical destination changed: ' + name)
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open('xb') as stream:
        stream.write(data)


def find_historical_files(roots, wanted, suffixes=None):
    """Find actual bytes, ignoring suggestive names and stale success reports."""
    suffixes = suffixes or {'.bin', '.npz', '.jpg', '.json', '.hex'}
    found = {}
    seen = set()
    for root in roots:
        root = Path(root).resolve()
        if not root.is_dir():
            continue
        command = ['rg', '--files', '--hidden', '--no-ignore']
        for suffix in sorted(suffixes):
            command += ['-g', '*' + suffix]
        result = subprocess.run(command + [str(root)], capture_output=True)
        require(result.returncode in (0, 1), 'asset inventory failed: ' + result.stderr.decode(errors='replace'))
        for line in result.stdout.decode('utf-8').splitlines():
            path = Path(line).resolve()
            if path in seen or not path.is_relative_to(root) or not path.is_file():
                continue
            seen.add(path)
            # Frozen B03 blobs are small; unrelated large build images cannot be inputs.
            if path.stat().st_size > 32 * 1024 * 1024:
                continue
            hashed = digest(path.read_bytes())
            if hashed in wanted and hashed not in found:
                found[hashed] = path
    return found


def _json(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')


def _closure(repo):
    all_paths = subprocess.check_output(['git', '-C', str(repo), 'ls-tree', '-r', '--name-only',
                                         REVISION, '--', 'yunet/python']).decode().splitlines()
    modules = {Path(name).stem: name for name in all_paths if name.endswith('.py')}
    pending, seen = ['compile_b03_runtime', 'program_abi'], set()
    while pending:
        name = pending.pop()
        if name in seen:
            continue
        seen.add(name)
        source = subprocess.check_output(['git', '-C', str(repo), 'show', REVISION + ':' + modules[name]])
        for node in ast.walk(ast.parse(source)):
            imported = ([node.module] if isinstance(node, ast.ImportFrom) else
                        [alias.name for alias in node.names] if isinstance(node, ast.Import) else [])
            pending.extend(item for item in imported if item in modules and item not in seen)
    return sorted(modules[name] for name in seen)


def _worker(output):
    """Execute only copies frozen before launch, with every output hash checked."""
    require(__debug__, 'optimized Python disables upstream checks; host PASS prohibited')
    output = Path(output).resolve()
    frozen, assets = output / 'frozen_upstream', output / 'assets'
    plan = json.loads((output / 'recovery_plan.json').read_text(encoding='utf-8'))
    verify_frozen(frozen, plan['frozen_sources_sha256'])
    manifest = load_manifest(frozen / MANIFEST_PATH)
    hashes = manifest['files_sha256']
    sys.path.insert(0, str(frozen / 'yunet/python'))
    import numpy as np
    import threadpoolctl
    import program_abi
    import compile_b03_runtime as compiler
    from b03_post_reference import DecodeTable
    mapping = json.loads((frozen / BASE_MANIFEST).read_bytes())
    old_program = (frozen / OLD / 'program.bin').read_bytes()
    image = (frozen / OLD / 'parameter_image.bin').read_bytes()
    require(digest(old_program) == mapping['program_sha256'] and
            digest(image) == mapping['parameter_image_sha256'], 'old package SHA mismatch')
    program = program_abi.unpack(old_program)
    program_abi.validate(program)
    params = program_abi.parameter_arrays(program, image, mapping['parameter_image_model_offset'])
    numeric = json.loads((frozen / NUMERICS).read_bytes())
    table = DecodeTable(numeric)
    table_bytes = np.concatenate(table.rows).astype('<u4').tobytes(order='C')
    heads = manifest['head_slot_map']
    runtime, decoded = compiler.build_runtime(program, mapping, image, heads, table_bytes, old_program)
    header, ops = compiler.decode_runtime(runtime)
    rejections = compiler.check_corruption_rejection(runtime)

    def put(name, raw):
        write_historical(assets, name, raw, hashes)

    def binary(name, raw):
        put(name + '.bin', raw)
        if name + '.hex' in hashes:
            require(len(raw) % 32 == 0, 'hex image alignment')
            text = ''.join(f'{int.from_bytes(raw[i:i+32], "little"):064x}\n' for i in range(0, len(raw), 32))
            # Historical exporter ran on Windows with Path.write_text newline translation.
            put(name + '.hex', text.replace('\n', '\r\n').encode('ascii'))

    binary('program', runtime)
    binary('parameter_image', image)
    binary('post_table', table_bytes)
    put('ops.hex', ''.join(f'{int.from_bytes(runtime[128*(i+1):128*(i+2)], "little"):0256x}\r\n'
                            for i in range(len(ops))).encode('ascii'))
    task, placement = compiler.frame_task(header, runtime)
    binary('frame_task', task)
    put('frame_task_template.json', (json.dumps(placement, ensure_ascii=False, indent=2) + '\n').replace('\n', '\r\n').encode())
    put('runtime_decoded.json', (json.dumps(decoded, ensure_ascii=False, indent=2) + '\n').replace('\n', '\r\n').encode())
    init = bytearray(b'\x00\x80' * (26368 // 2))
    for row in heads:
        if row['name'].startswith(('cls_', 'obj_')):
            start = row['slot_offset']
            init[start:start + row['allocated_bytes']] = b'\xff\xff' * (row['allocated_bytes'] // 2)
    binary('heads_init', init)
    print('B03_CORE_RECOVERED ' + str(assets), flush=True)

    historical_heads = {row['name']: row for row in json.loads((frozen / HEAD_GOLD).read_bytes())['cases']}
    post_frozen = json.loads((frozen / POST).read_bytes())
    cases, unavailable = [], []
    # Freeze all loaded reference/runtime modules before numerical execution.
    runtime_files = {str(Path(module.__file__).resolve()): digest(Path(module.__file__).read_bytes())
                     for module in list(sys.modules.values())
                     if getattr(module, '__file__', None) and Path(module.__file__).is_file()}
    for dll in (Path(np.__file__).parent.parent / 'numpy.libs').glob('*.dll'):
        runtime_files[str(dll.resolve())] = digest(dll.read_bytes())
    for index, name in enumerate(CASES):
        path = frozen / 'recovered_inputs' / (name + '.bin')
        kind = 'recovered historical input bytes'
        if name == 'zero':
            inp = bytes(307200)
            kind = 'deterministic zero U8 NCHW input'
        elif name == 'full255':
            inp = bytes([255]) * 307200
            kind = 'deterministic full255 U8 NCHW input'
        elif name == 'pattern':
            grid = np.indices((1, 3, 320, 320))
            inp = ((grid[1] * 83 + grid[2] * 7 + grid[3] * 13) % 256).astype(np.uint8).tobytes()
            kind = 'deterministic (channel*83 + row*7 + column*13) modulo 256'
        elif path.is_file():
            inp = path.read_bytes()
        else:
            unavailable.append({'case': name, 'reason': 'historical natural-image input bytes missing',
                                'input_sha256': hashes[f'cases/{name}/input.bin']})
            continue
        require(len(inp) == 307200 and digest(inp) == hashes[f'cases/{name}/input.bin'], 'case input identity')
        geom = dict(source_width=320, source_height=320, resized_width=320, resized_height=320, pad_left=0, pad_top=0)
        if name.startswith('wider_'):
            task_path = assets / 'cases' / name / 'task.bin'
            if not task_path.is_file():
                unavailable.append({'case': name, 'reason': 'historical task/letterbox geometry missing'})
                continue
            words = struct.unpack('<32I', task_path.read_bytes())
            geom = dict(zip(geom, words[19:25]))
        tensor = np.frombuffer(inp, dtype=np.uint8).reshape(1, 3, 320, 320)
        with threadpoolctl.threadpool_limits(limits=2, user_api='blas'):
            values = program_abi.reference_from_wire(program, params, tensor)
        golden = {mapping['tensor_names'][row['id']]: values[row['id']].astype(compiler.DTYPE[row['dtype']])
                  for row in program['tensors']}
        if name in historical_heads:
            for row in historical_heads[name]['head_files']:
                require(digest(golden[row['name']].tobytes()) == row['sha256'], 'historical individual head mismatch')
        replay = compiler.replay(runtime, image, inp, golden, decoded['tensor_refs'], heads, table,
                                 [row for row in post_frozen['head_cases'] if row['name'] == name], geom)
        prefix = f'cases/{name}/'
        binary(prefix + 'input', inp)
        binary(prefix + 'heads_golden', replay['heads_bytes'])
        put(prefix + 'records_golden.bin', replay['records_bytes'])
        task, _ = compiler.frame_task(header, runtime, frame_id=index + 1, cmd_id=0xb0300000 + index,
            source_w=geom['source_width'], source_h=geom['source_height'], resized_w=geom['resized_width'],
            resized_h=geom['resized_height'], pad_left=geom['pad_left'], pad_top=geom['pad_top'])
        binary(prefix + 'task', task)
        row = {'name': name, 'input_provenance': kind, 'geometry': geom, 'face_count': replay['face_count'],
               'tensor_comparisons': len(replay['tensors']), 'tensors': replay['tensors'],
               'historical_combined_head_sha256': digest(replay['heads_bytes']),
               'historical_records_sha256': digest(replay['records_bytes'])}
        cases.append(row)
        print('B03_CASE_RECOVERED ' + name + ' tensors=' + str(len(replay['tensors'])), flush=True)
    verify_frozen(frozen, plan['frozen_sources_sha256'])
    for path, expected in runtime_files.items():
        require(digest(Path(path).read_bytes()) == expected, 'host runtime changed: ' + path)
    report = {'scope': 'Old format1 reference versus NPM3 address replay; historical input/head/record SHA validation; no RTL.',
              'tensor_comparisons': sum(row['tensor_comparisons'] for row in cases), 'cases': cases,
              'unavailable_cases': unavailable, 'malformed_runtime_rejections': rejections,
              'python': sys.version, 'numpy': np.__version__, 'runtime_files_sha256': runtime_files}
    _json(output / 'host_reference.json', report)
    return report


def prepare(output, npu_root, *, search_roots=None, python_executable=None):
    output, npu_root = Path(output).resolve(), Path(npu_root).resolve()
    require(not output.exists(), 'output already exists; refusing to overwrite evidence')
    require(__debug__, 'optimized Python disables upstream checks')
    output.mkdir(parents=True)
    frozen, assets = output / 'frozen_upstream', output / 'assets'
    assets.mkdir()
    expected = {MANIFEST_PATH: MANIFEST_SHA256}
    records = freeze_git_inputs(npu_root, REVISION, [MANIFEST_PATH], frozen, expected)
    manifest = load_manifest(frozen / MANIFEST_PATH)
    expected.update(manifest['source_sha256'])
    expected[BASE_MANIFEST] = expected[OLD + '/program_package_manifest_v0_1.json']
    names = _closure(npu_root) + [BASE_MANIFEST, NUMERICS, POST, HEAD_MAP, HEAD_GOLD]
    # Historical compiler snapshot documents are independently immutable Git blobs.
    snapshots = {name.removeprefix('inputs_snapshot/'): name for name in manifest['files_sha256']
                 if name.startswith('inputs_snapshot/')}
    names = sorted(set(names) | snapshots.keys())
    records.update(freeze_git_inputs(npu_root, REVISION, names, frozen, expected))
    for source, dest in snapshots.items():
        write_historical(assets, dest, (frozen / source).read_bytes(), manifest['files_sha256'])
    roots = [npu_root / 'build/integration_audit/20261020', npu_root / 'yunet'] + list(search_roots or [])
    wanted = set(manifest['files_sha256'].values()) | {expected[OLD + '/' + leaf] for leaf in ('program.bin', 'parameter_image.bin')}
    found = find_historical_files(roots, wanted)
    provenance = {}
    for name, hashed in manifest['files_sha256'].items():
        if hashed in found:
            write_historical(assets, name, found[hashed].read_bytes(), manifest['files_sha256'])
            provenance[name] = {'source': str(found[hashed]), 'sha256': hashed, 'kind': 'existing bytes'}
    missing_inputs = []
    for leaf in ('program.bin', 'parameter_image.bin'):
        name = OLD + '/' + leaf
        hashed = expected[name]
        if hashed not in found:
            missing_inputs.append({'path': name, 'sha256': hashed})
        else:
            freeze_file(found[hashed], frozen / name, hashed)
            records[name] = hashed
            provenance[name] = {'source': str(found[hashed]), 'sha256': hashed, 'kind': 'existing bytes'}
    for name in CASES:
        hashed = manifest['files_sha256'][f'cases/{name}/input.bin']
        if hashed in found:
            dest = 'recovered_inputs/' + name + '.bin'
            freeze_file(found[hashed], frozen / dest, hashed)
            records[dest] = hashed
            provenance[dest] = {'source': str(found[hashed]), 'sha256': hashed, 'kind': 'existing bytes'}
    plan = {'upstream_revision': REVISION, 'historical_manifest_sha256': MANIFEST_SHA256,
            'frozen_sources_sha256': records, 'provenance': provenance, 'search_roots': [str(p) for p in roots],
            'missing_generator_inputs': missing_inputs}
    _json(output / 'recovery_plan.json', plan)
    # Worker imports neither the mutable checkout nor the mutable main scripts.
    tools = output / 'tool_snapshot'
    tools.mkdir()
    tool_hashes = {}
    for name in ('prepare_b03_assets.py', 'audit_b03_assets.py'):
        src = Path(__file__).with_name(name)
        hashed = digest(src.read_bytes())
        freeze_file(src, tools / name, hashed)
        tool_hashes[name] = hashed
    host = {'tensor_comparisons': 0, 'cases': [], 'unavailable_cases': []}
    if not missing_inputs:
        executable = Path(python_executable) if python_executable else npu_root / '.venv/Scripts/python.exe'
        require(executable.is_file(), 'existing numeric Python runtime missing')
        log = output / 'worker.log'
        with log.open('w', encoding='utf-8') as stream:
            result = subprocess.run([str(executable), '-B', str(tools / 'prepare_b03_assets.py'),
                                     '--worker', str(output)], stdout=stream, stderr=subprocess.STDOUT)
        require(result.returncode == 0, 'B03 recovery worker failed; see ' + str(log))
        host = json.loads((output / 'host_reference.json').read_bytes())
    verify_frozen(frozen, records)
    verify_frozen(tools, tool_hashes)
    report = audit_assets(assets, frozen / MANIFEST_PATH)
    report.update(created_utc=datetime.now(timezone.utc).isoformat(), frozen_sources_sha256=records,
                  tool_snapshot_sha256=tool_hashes, provenance=provenance, host_reference=host,
                  search_roots=plan['search_roots'], missing_generator_inputs=missing_inputs)
    _json(output / 'recovery_report.json', report)
    return report


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path)
    parser.add_argument('--npu-root', type=Path, default=Path('D:/FPGA/npu_zgtc'))
    parser.add_argument('--search-root', action='append', type=Path, default=[])
    parser.add_argument('--python', type=Path)
    parser.add_argument('--worker', type=Path, help=argparse.SUPPRESS)
    args = parser.parse_args()
    if args.worker:
        _worker(args.worker)
        return 0
    require(args.output is not None, '--output is required')
    existed = args.output.exists()
    try:
        report = prepare(args.output, args.npu_root, search_roots=args.search_root, python_executable=args.python)
    except Exception as exc:
        if not existed and args.output.is_dir():
            _json(args.output / 'recovery_report.json', {'status': 'FAIL', 'error': str(exc),
                  'RTL_executed': False, 'board_verified': False})
        print(str(exc), file=sys.stderr)
        return 1
    print(json.dumps({key: report[key] for key in ('status', 'matched_count', 'core_ready', 'runtime_ready_cases')}, indent=2))
    return 0 if report['status'] == 'PASS_HOST_ASSETS_ONLY' else 2 if report['status'] == 'PARTIAL' else 1


if __name__ == '__main__':
    sys.exit(main())
