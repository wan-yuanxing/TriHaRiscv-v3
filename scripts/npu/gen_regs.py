"""Generate the NPU operator RTL/C register definitions from one strict JSON ABI."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[2]
IDENTIFIER = re.compile(r"[A-Z][A-Z0-9_]*\Z")
RW_NAMES = set("""IRQ_ENABLE OP_TAG FRAME_ID GENERATION INPUT_BASE WEIGHT_BASE
BIAS_BASE REQUANT_BASE OUTPUT_BASE INPUT_WH CHANNELS OUTPUT_WH KSP FORMAT""".split())
RO_NAMES = set("""ID_VERSION CAPS STATUS ERROR_CODE TOTAL_CYCLES COMPUTE_CYCLES
DMA_WAIT_CYCLES""".split())
REQUIRED_NAMES = RW_NAMES | RO_NAMES | {"CONTROL", "IRQ_STATUS"}


def require(condition, message):
    if not condition:
        raise ValueError(message)


def integer(value, low, high):
    return type(value) is int and low <= value <= high


def unique_object(pairs):
    result = {}
    for key, value in pairs:
        require(key not in result, "duplicate JSON key: " + key)
        result[key] = value
    return result


def validate(config):
    require(type(config) is dict, "register profile must be an object")
    require(set(config) == {"schema_version", "base", "region_bytes", "id_version", "caps", "registers"},
            "unexpected profile keys")
    fixed = {"schema_version": 1, "base": 0x20000000, "region_bytes": 4096,
             "id_version": 0x4e500001, "caps": 0x00010003}
    for key, value in fixed.items():
        require(type(config[key]) is int and config[key] == value, "invalid fixed " + key)
    registers = config["registers"]
    require(type(registers) is list and len(registers) == len(REQUIRED_NAMES), "invalid register table")
    names = set()
    offsets = set()
    for reg in registers:
        require(type(reg) is dict, "register must be an object")
        require({"name", "offset", "access", "fields"} <= set(reg) <=
                {"name", "offset", "access", "fields", "reset"}, "invalid register keys")
        name, offset, access = reg["name"], reg["offset"], reg["access"]
        require(type(name) is str and bool(IDENTIFIER.fullmatch(name)) and
                name in REQUIRED_NAMES and name not in names, "invalid/duplicate register name")
        require(integer(offset, 0, config["region_bytes"] - 4) and offset % 4 == 0 and
                offset not in offsets, "invalid/duplicate register offset")
        expected_access = "RW" if name in RW_NAMES else "RO" if name in RO_NAMES else "WO" if name == "CONTROL" else "W1C"
        require(access == expected_access, "invalid register access")
        fields = reg["fields"]
        require(type(fields) is list, "fields must be an array")
        field_names = set()
        used = 0
        for field in fields:
            require(type(field) is dict and set(field) == {"name", "lsb", "width"}, "invalid field keys")
            field_name, lsb, width = field["name"], field["lsb"], field["width"]
            require(type(field_name) is str and bool(IDENTIFIER.fullmatch(field_name)) and
                    field_name not in field_names, "invalid/duplicate field name")
            require(integer(lsb, 0, 31) and integer(width, 1, 32) and lsb + width <= 32,
                    "invalid field range")
            mask = ((1 << width) - 1) << lsb
            require(not used & mask, "overlapping register fields")
            used |= mask
            field_names.add(field_name)
        if access == "RO":
            require("reset" not in reg, "RO registers must not define reset")
        else:
            reset = reg.get("reset")
            require(integer(reset, 0, 0xffffffff) and (not fields or not reset & ~used),
                    "invalid writable reset")
        names.add(name)
        offsets.add(offset)
    require(names == REQUIRED_NAMES, "incomplete NPU ABI")


def generated_files(config, digest):
    validate(config)
    require(type(digest) is str and bool(re.fullmatch(r"[0-9a-f]{64}", digest)), "invalid source digest")
    values = {"NPU_MMIO_BASE": config["base"], "NPU_MMIO_BYTES": config["region_bytes"],
              "NPU_ID_VERSION": config["id_version"], "NPU_CAPS": config["caps"]}
    for reg in sorted(config["registers"], key=lambda item: item["offset"]):
        name = reg["name"]
        values["NPU_REG_" + name] = reg["offset"]
        if "reset" in reg:
            values["NPU_REG_" + name + "_RESET"] = reg["reset"]
        used = 0
        for field in sorted(reg["fields"], key=lambda item: item["lsb"]):
            prefix = "NPU_" + name + "_" + field["name"]
            mask = ((1 << field["width"]) - 1) << field["lsb"]
            values[prefix + "_MASK"] = mask
            values[prefix + "_SHIFT"] = field["lsb"]
            used |= mask
        values["NPU_REG_" + name + "_VALID_MASK"] = used if reg["fields"] else 0xffffffff
    note = "// Generated by scripts/npu/gen_regs.py; config SHA256 " + digest + "\n"
    rtl = note + "`ifndef TRIHA_NPU_REGS_VH\n`define TRIHA_NPU_REGS_VH\n"
    header = note + "#ifndef TRIHA_NPU_REGS_H\n#define TRIHA_NPU_REGS_H\n"
    for name, value in values.items():
        rtl += f"`define {name} 32'h{value:08x}\n"
        header += f"#define {name} 0x{value:08x}u\n"
    return {"rtl/npu/include/npu_regs.vh": rtl + "`endif\n",
            "sw/include/npu_regs.h": header + "#endif\n"}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=ROOT)
    parser.add_argument("--config", type=Path, default=ROOT / "config/npu_regs.json")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    try:
        raw = args.config.read_bytes()
        config = json.loads(raw, object_pairs_hook=unique_object)
        files = generated_files(config, hashlib.sha256(raw).hexdigest())
        stale = []
        for name, content in files.items():
            target = args.root / name
            data = content.encode("utf-8")
            if args.check:
                if not target.is_file() or target.read_bytes() != data:
                    stale.append(name)
            else:
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_bytes(data)
        require(not stale, "missing/stale generated register files: " + ", ".join(stale))
    except (OSError, ValueError, TypeError, KeyError) as error:
        print("NPU_REGS_FAIL:", error, file=sys.stderr)
        return 1
    print("NPU_REGS_PASS" + (" check" if args.check else " generate"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
